// Bundle the TypeScript sim core into a single browser <script> block, with no
// third-party toolchain: Node's built-in type stripper does the work.
//
// Why: the web prototype and the Monte Carlo harness must run the SAME economy.
// Two copies of the balance would drift within a day.
//
// Run: node tools/build-web.ts   → writes web/sim.bundle.js

import { stripTypeScriptTypes } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

// dependency order matters: no module system in the output
const FILES = [
  'sim/rng.ts',
  'sim/types.ts',
  'sim/whales.ts',
  'sim/cards.ts',
  'sim/engine.ts',
  'sim/policies.ts',
];

const EXPORTS = [
  'makeRng',
  'seedFromString',
  'COHORTS',
  'SLOTS',
  'CARDS',
  'CARD_BY_ID',
  'deckForTier',
  'WHALE_SEEDS',
  'newWhales',
  'NEUTRAL_DIALS',
  'defaultConfig',
  'newRun',
  'advanceWeek',
  'exploitIntensity',
  'board',
  'synergyMult',
  'affinityHits',
  'isSeasonStart',
  'pushPreview',
  'PUSH_MULT',
  'PUSH_RISK',
  'MAX_PUSH',
  'pace',
  'POLICIES',
  'readout',
];

function transpile(src: string): string {
  const stripped = stripTypeScriptTypes(src, { mode: 'strip' });
  return (
    stripped
      // no module system in the bundle: drop imports, unwrap exports
      .replace(/^\s*import[\s\S]*?from\s*['"][^'"]+['"];?[ \t]*$/gm, '')
      .replace(/^export\s+/gm, '')
      .trimEnd()
  );
}

const parts = FILES.map((f) => {
  const code = transpile(readFileSync(join(root, f), 'utf8'));
  return `// ─── ${f} ${'─'.repeat(Math.max(0, 60 - f.length))}\n${code}`;
});

const bundle = `// GENERATED by tools/build-web.ts — do not edit. Source of truth: apps/whale-farm/sim/
(function (global) {
'use strict';

${parts.join('\n\n')}

global.WF = { ${EXPORTS.join(', ')} };
})(typeof window !== 'undefined' ? window : globalThis);
`;

mkdirSync(join(root, 'web'), { recursive: true });
writeFileSync(join(root, 'web/sim.bundle.js'), bundle);

// Smoke test: the bundle must run in a bare scope and finish a full quarter,
// otherwise we would ship a broken prototype without noticing.
// the bundle's IIFE takes `globalThis` as its host object, so a plain object works
const host: Record<string, any> = {};
new Function('globalThis', bundle)(host);
const WF = host.WF;
if (!WF) throw new Error('bundle produced no WF global');

let s = WF.newRun(WF.defaultConfig(42));
let guard = 0;
while (s.status === 'running' && guard++ < 50) {
  s = WF.advanceWeek(s, WF.POLICIES.builder(s, () => 0.5));
}
if (s.status === 'running') throw new Error('bundle smoke test never terminated');

console.log(
  `web/sim.bundle.js  ${(bundle.length / 1024).toFixed(1)} KB  ` +
    `(smoke: ${s.status}, $${(s.revenue / 1e6).toFixed(2)}M in ${s.log.length} weeks)`,
);

// ── inline the bundle into the playable prototype ───────────────────────────────
// The prototype must be a single self-contained file (that is what an Artifact
// publish accepts, and it is also how the owner plays it on a phone).
const template = readFileSync(join(root, 'web/index.template.html'), 'utf8');
const MARKER = '/* SIM_BUNDLE */';
if (!template.includes(MARKER)) throw new Error(`template is missing ${MARKER}`);
const html = template.replace(MARKER, bundle);

// cheap structural checks — a broken prototype that still "builds" is worse than a crash
for (const id of ['btnRun', 'cards', 'cohorts', 'overlay', 'stance']) {
  if (!html.includes(`id="${id}"`)) throw new Error(`prototype lost #${id}`);
}
if (html.includes(MARKER)) throw new Error('bundle injection failed');

writeFileSync(join(root, 'web/prototype.html'), html);
console.log(`web/prototype.html ${(html.length / 1024).toFixed(1)} KB  (self-contained)`);
