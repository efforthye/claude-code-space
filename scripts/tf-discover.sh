#!/usr/bin/env bash
# tf-discover — read the REAL state of the home-server mini and emit what
# Terraform needs to adopt it, without ever printing a secret.
#
# Run this ON THE MINI, from the repo root:
#
#   ./scripts/tf-discover.sh
#
# It produces two things:
#   1. raw/terraform-discovery.md          — a redacted snapshot to ingest into the wiki
#   2. infra/terraform/onprem/imports.generated.tf — ready-to-use `import` blocks (gitignored)
#
# SAFETY: environment variables are reduced to their KEY NAMES only. Values
# (richclub DB credentials, API keys, …) are never read into the output. Same
# for Cloudflare — tunnel UUIDs and record IDs are identifiers, not credentials;
# the tunnel credentials JSON is never touched.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT_MD="$REPO_ROOT/raw/terraform-discovery.md"
OUT_TF="$REPO_ROOT/infra/terraform/onprem/imports.generated.tf"
CONTAINERS=(richclub-api richclub-front jenkins mayo-api)
ZONE="efforthye.dev"

command -v docker >/dev/null 2>&1 || { echo "ERROR: docker not found — run this on the mini." >&2; exit 127; }
docker info >/dev/null 2>&1 || { echo "ERROR: docker daemon unreachable — is Docker Desktop running?" >&2; exit 1; }

echo "# Terraform discovery — home-server mini" > "$OUT_MD"
{
  echo
  echo "Generated by \`scripts/tf-discover.sh\` on \`$(hostname)\` at $(date '+%Y-%m-%d %H:%M:%S')."
  echo "Env values are redacted to key names only."
  echo
  echo "## Docker containers"
} >> "$OUT_MD"

echo "// Generated by scripts/tf-discover.sh — do not edit by hand." > "$OUT_TF"
echo "// Remove each block once \`terraform plan\` shows the resource as adopted." >> "$OUT_TF"
echo >> "$OUT_TF"

for name in "${CONTAINERS[@]}"; do
  if ! docker container inspect "$name" >/dev/null 2>&1; then
    echo "- \`$name\` — NOT RUNNING (no Terraform resource needed yet)" >> "$OUT_MD"
    continue
  fi

  cid="$(docker container inspect "$name" --format '{{.Id}}')"

  {
    echo
    echo "### \`$name\`"
    echo '```'
    docker container inspect "$name" --format \
      'id:      {{.Id}}
image:   {{.Config.Image}}
imageId: {{.Image}}
restart: {{.HostConfig.RestartPolicy.Name}}
network: {{.HostConfig.NetworkMode}}
ports:   {{range $p, $b := .HostConfig.PortBindings}}{{range $b}}{{.HostPort}}->{{$p}} {{end}}{{end}}
mounts:  {{range .Mounts}}[{{.Type}} {{if .Name}}{{.Name}}{{else}}{{.Source}}{{end}} -> {{.Destination}}{{if .RW}} rw{{else}} ro{{end}}] {{end}}
envKeys: {{range .Config.Env}}{{index (split . "=") 0}} {{end}}
cmd:     {{if .Config.Cmd}}{{join .Config.Cmd " "}}{{end}}
entry:   {{if .Config.Entrypoint}}{{join .Config.Entrypoint " "}}{{end}}'
    echo '```'
  } >> "$OUT_MD"

  tf_name="${name//-/_}"
  {
    echo "import {"
    echo "  to = docker_container.${tf_name}"
    echo "  id = \"${cid}\""
    echo "}"
    echo
  } >> "$OUT_TF"
done

# ---------------------------------------------------------------- Cloudflare
{
  echo
  echo "## Cloudflare"
} >> "$OUT_MD"

if command -v cloudflared >/dev/null 2>&1; then
  {
    echo
    echo "### Named tunnels (\`cloudflared tunnel list\`)"
    echo '```'
    cloudflared tunnel list 2>&1 || echo "(failed — is ~/.cloudflared/cert.pem present?)"
    echo '```'
    echo
    echo "Put the UUIDs above into \`infra/terraform/onprem/terraform.tfvars\`:"
    echo "\`richclub_tunnel_id\` and \`mayo_api_tunnel_id\`."
  } >> "$OUT_MD"
else
  echo "- \`cloudflared\` not found on PATH." >> "$OUT_MD"
fi

{
  echo
  echo "### DNS records — needs an API token"
  echo
  echo "Terraform imports DNS records by \`<zone_id>/<record_id>\`. With a token"
  echo "exported (\`CLOUDFLARE_API_TOKEN\`, Zone:DNS:Read is enough for this step):"
  echo
  echo '```bash'
  echo "ZONE_ID=\$(curl -s -H \"Authorization: Bearer \$CLOUDFLARE_API_TOKEN\" \\"
  echo "  \"https://api.cloudflare.com/client/v4/zones?name=$ZONE\" \\"
  echo "  | python3 -c 'import sys,json;print(json.load(sys.stdin)[\"result\"][0][\"id\"])')"
  echo
  echo "curl -s -H \"Authorization: Bearer \$CLOUDFLARE_API_TOKEN\" \\"
  echo "  \"https://api.cloudflare.com/client/v4/zones/\$ZONE_ID/dns_records?type=CNAME\" \\"
  echo "  | python3 -c 'import sys,json;[print(r[\"id\"], r[\"name\"], r[\"content\"]) for r in json.load(sys.stdin)[\"result\"]]'"
  echo '```'
  echo
  echo "Then append one block per record to \`infra/terraform/onprem/imports.generated.tf\`:"
  echo
  echo '```hcl'
  echo 'import {'
  echo '  to = cloudflare_dns_record.tunnel["richclub.efforthye.dev"]'
  echo '  id = "<zone_id>/<record_id>"'
  echo '}'
  echo '```'
} >> "$OUT_MD"

echo
echo "Wrote:"
echo "  $OUT_MD"
echo "  $OUT_TF"
echo
echo "Next: copy terraform.tfvars.example -> terraform.tfvars, fill it in, then"
echo "  cd infra/terraform/onprem && terraform init && terraform plan"
echo "Read the plan carefully — nothing should be destroyed or replaced."